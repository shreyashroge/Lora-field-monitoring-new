(() => {
  const API = (window.API_BASE || '').replace(/\/$/, '');
  const $ = (id) => document.getElementById(id);
  const rnd = (a, b, d = 1) => +(a + Math.random() * (b - a)).toFixed(d);
  const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

  // mode: 'demo' = everything generated in this browser; 'live' = data from the backend API
  const S = { mode: 'demo', node: 'FIELD-01', nodes: [], history: [], intervalMin: 15, seq: 0, simEnabled: true };

  async function api(path, opts = {}, timeout = 6000) {
    const ctl = new AbortController();
    const t = setTimeout(() => ctl.abort(), timeout);
    try {
      const res = await fetch(API + path, { ...opts, signal: ctl.signal });
      const body = await res.json().catch(() => null);
      if (!res.ok || body === null) throw new Error((body && body.error) || 'HTTP ' + res.status);
      return body;
    } finally {
      clearTimeout(t);
    }
  }

  // ---------- demo-mode packet (generated locally in the browser) ----------
  function demoPacket() {
    S.seq += 1;
    const now = new Date().toISOString();
    return {
      id: 'demo-' + S.seq,
      demo_status: 'SIMULATED_NOT_HARDWARE',
      source: 'demo',
      node_id: 'FIELD-01',
      sequence: S.seq,
      timestamp: now,
      received_at: now,
      soil_moisture_percent: rnd(25, 70),
      soil_temperature_C: rnd(21, 31),
      air_temperature_C: rnd(24, 36),
      relative_humidity_percent: rnd(34, 82),
      atmospheric_pressure_hPa: rnd(997, 1017),
      light_intensity_lux: Math.round(rnd(1200, 36000, 0)),
      battery_voltage_V: rnd(3.62, 4.16, 2),
      proposed_reporting_interval_minutes: 15,
    };
  }

  // ---------- rendering ----------
  const latest = () => S.history[S.history.length - 1];

  function eventLabel(p) {
    if (p.source === 'hardware') return ['Received from gateway', 'hw'];
    if (p.source === 'simulated') return ['Generated by server (simulated)', ''];
    return ['Payload generated (local demo)', ''];
  }

  function updateStatus() {
    const chip = $('statusChip');
    chip.className = 'status';
    const t = $('statusText');
    if (S.mode === 'demo') { t.textContent = 'SIMULATION MODE (LOCAL)'; return; }
    const p = latest();
    if (!p) { t.textContent = 'LIVE · NO DATA YET'; return; }
    if (p.source === 'simulated') { t.textContent = 'LIVE · SIMULATED NODE'; return; }
    const ageMin = (Date.now() - Date.parse(p.received_at)) / 60000;
    if (ageMin < S.intervalMin * 2) { chip.classList.add('live'); t.textContent = 'LIVE · NODE ONLINE'; }
    else { chip.classList.add('off'); t.textContent = 'LIVE · NODE OFFLINE (' + Math.round(ageMin) + ' min)'; }
  }

  function updateNotice() {
    const n = $('notice');
    n.className = 'notice';
    const p = latest();
    if (S.mode === 'demo') {
      n.innerHTML = '<strong>DEMO DATA — NOT CONNECTED TO HARDWARE.</strong> Values on this page are generated locally in your browser (no backend is reachable). No sensor, LoRa radio, solar panel or battery is connected; this is not a live telemetry dashboard.';
    } else if (!p) {
      n.innerHTML = '<strong>BACKEND CONNECTED.</strong> No readings yet. Press “Generate reading” for a simulated one, or start a gateway / <code>simulator.js</code>.';
    } else if (p.source === 'simulated') {
      n.innerHTML = '<strong>SIMULATED DATA.</strong> This node’s values were generated by the server for demonstration, not measured by sensors.';
    } else {
      n.classList.add('ok');
      n.innerHTML = '<strong>RECEIVING GATEWAY DATA.</strong> Readings below were posted to the backend by the LoRa gateway.';
    }
  }

  function clearView() {
    for (const id of ['moist', 'soilT', 'airT', 'rh', 'pressure', 'lux', 'battery', 'powerV']) $(id).textContent = '—';
    $('count').textContent = S.mode === 'demo' ? '0' : '—';
    $('countNote').textContent = S.mode === 'demo' ? 'Local simulation counter' : '';
    $('updated').textContent = 'Waiting for first reading';
    $('state').textContent = 'Awaiting data';
    $('barFill').style.width = '0%';
    $('packetTag').textContent = '0 EVENTS';
    $('logBody').innerHTML = '<tr><td colspan="4" class="muted">No events yet. Generate a reading to begin.</td></tr>';
    $('json').textContent = 'No payload generated yet.';
    drawChart();
  }

  function drawChart() {
    const a = S.history.slice(-8);
    if (!a.length) { $('moistLine').setAttribute('d', ''); $('tempLine').setAttribute('d', ''); return; }
    const coords = (key, min, max) => a.map((p, i) => {
      const x = a.length === 1 ? 311 : 42 + i * (538 / (a.length - 1));
      const y = 145 - (p[key] - min) / (max - min) * 120;
      return [x, Math.max(25, Math.min(145, y))];
    });
    const path = (c) => {
      // a single reading has no line to draw, so show it as a dot (round line caps)
      if (c.length === 1) return 'M' + c[0][0].toFixed(1) + ' ' + c[0][1].toFixed(1) + ' L' + (c[0][0] + 0.1).toFixed(1) + ' ' + c[0][1].toFixed(1);
      return c.map((p, i) => (i ? 'L' : 'M') + p[0].toFixed(1) + ' ' + p[1].toFixed(1)).join(' ');
    };
    $('moistLine').setAttribute('d', path(coords('soil_moisture_percent', 20, 80)));
    $('tempLine').setAttribute('d', path(coords('air_temperature_C', 20, 40)));
  }

  function render() {
    const p = latest();
    updateStatus();
    updateNotice();
    $('countLabel').textContent = S.mode === 'demo' ? 'Packets created' : 'Packets received';
    if (!p) { clearView(); return; }

    $('nodeLabel').textContent = p.node_id;
    $('moist').textContent = p.soil_moisture_percent;
    $('soilT').textContent = p.soil_temperature_C;
    $('airT').textContent = p.air_temperature_C;
    $('rh').textContent = p.relative_humidity_percent;
    $('pressure').textContent = p.atmospheric_pressure_hPa;
    $('lux').textContent = Number(p.light_intensity_lux).toLocaleString();
    const v = Number(p.battery_voltage_V);
    $('battery').textContent = v.toFixed(2);
    $('powerV').textContent = v.toFixed(2);
    const simLabel = p.source !== 'hardware';
    $('batteryNote').textContent = v < 3.7 ? (simLabel ? 'Illustrative low-voltage flag' : 'Low voltage reported') : (simLabel ? 'Simulated voltage only' : 'Voltage reported by node');
    $('state').textContent = (v < 3.7 ? 'Low voltage' : v < 3.85 ? 'Watch' : 'Normal range') + (simLabel ? ' (simulated)' : '');
    $('barFill').style.width = Math.max(0, Math.min(100, (v - 3.3) / (4.2 - 3.3) * 100)) + '%';
    $('updated').textContent = 'Updated ' + new Date(p.received_at || p.timestamp).toLocaleTimeString();
    $('chartTag').textContent = simLabel ? 'SIMULATED' : 'GATEWAY DATA';
    $('trendNote').textContent = simLabel ? 'Illustrative simulated values' : 'Values received from the gateway';
    $('gwNote').textContent = S.mode === 'demo' ? 'Example payload handling · no RF reception occurs' : 'Packets received by the backend API';

    // packet card
    if (S.mode === 'demo') {
      $('count').textContent = S.seq;
      $('countNote').textContent = 'Local simulation counter';
    } else {
      const ns = S.nodes.find((n) => n.node_id === p.node_id);
      $('count').textContent = ns ? ns.received : S.history.length;
      const bits = [];
      if (ns) bits.push('Delivery ' + ns.delivery_ratio_percent + '%');
      if (p.rssi_dBm !== undefined) bits.push('RSSI ' + p.rssi_dBm + ' dBm');
      if (p.snr_dB !== undefined) bits.push('SNR ' + p.snr_dB + ' dB');
      $('countNote').textContent = bits.join(' · ') || 'Last seq ' + p.sequence;
    }

    // packet log (last 6)
    const rows = S.history.slice(-6).reverse().map((q) => {
      const [label, cls] = eventLabel(q);
      return `<tr><td class="sequence">${String(q.sequence).padStart(3, '0')}</td><td>${esc(q.node_id)}</td><td><span class="rx ${cls}">${label}</span></td><td>${new Date(q.received_at || q.timestamp).toLocaleTimeString()}</td></tr>`;
    });
    $('logBody').innerHTML = rows.join('');
    $('packetTag').textContent = rows.length + ' EVENTS';
    $('json').textContent = JSON.stringify(p, null, 2);
    drawChart();
  }

  // ---------- live mode ----------
  function fillNodeSelect() {
    const sel = $('nodeSelect');
    sel.innerHTML = '';
    for (const n of S.nodes) {
      const o = document.createElement('option');
      o.value = n.node_id;
      o.textContent = n.node_id + (n.source === 'simulated' ? ' (simulated)' : '');
      if (n.node_id === S.node) o.selected = true;
      sel.appendChild(o);
    }
    sel.hidden = S.nodes.length < 2;
    $('nodeLabel').hidden = S.nodes.length >= 2;
  }

  async function loadStats() {
    const s = await api('/api/stats');
    S.intervalMin = s.report_interval_min;
    S.nodes = s.nodes;
    $('intervalLabel').textContent = S.intervalMin;
    fillNodeSelect();
  }

  async function loadHistory() {
    if (!S.node) { S.history = []; render(); return; }
    const d = await api('/api/readings?limit=100&node_id=' + encodeURIComponent(S.node));
    S.history = d.readings;
    $('csv').href = API + '/api/readings.csv?node_id=' + encodeURIComponent(S.node);
    $('csv').hidden = false;
    render();
  }

  function addReading(r) {
    if (!S.node) { S.node = r.node_id; fillNodeSelect(); }
    if (r.node_id !== S.node) return;
    if (S.history.some((x) => x.id === r.id)) return;
    S.history.push(r);
    if (S.history.length > 100) S.history.shift();
    $('csv').hidden = false;
    $('csv').href = API + '/api/readings.csv?node_id=' + encodeURIComponent(S.node);
    render();
  }

  function connectStream() {
    const es = new EventSource(API + '/api/stream');
    es.onmessage = async (ev) => {
      let r;
      try { r = JSON.parse(ev.data); } catch (e) { return; }
      try { await loadStats(); } catch (e) { /* keep going */ }
      addReading(r);
    };
  }

  // ---------- events ----------
  $('generate').addEventListener('click', async () => {
    if (S.mode === 'demo') { addDemo(); return; }
    const btn = $('generate');
    btn.disabled = true;
    try {
      const r = await api('/api/simulate', { method: 'POST' });
      try { await loadStats(); } catch (e) { /* ignore */ }
      addReading(r);
    } catch (e) {
      alert('Could not generate a reading: ' + e.message);
    }
    btn.disabled = false;
  });

  function addDemo() {
    S.history.push(demoPacket());
    S.history = S.history.slice(-100);
    render();
  }

  $('reset').addEventListener('click', () => {
    S.history = [];
    if (S.mode === 'demo') S.seq = 0;
    render();
    if (S.mode === 'live') $('updated').textContent = 'View cleared · new readings will appear here';
  });

  $('copy').addEventListener('click', async () => {
    const p = latest();
    if (!p) { alert('Generate a reading first.'); return; }
    try {
      await navigator.clipboard.writeText(JSON.stringify(p, null, 2));
      alert('Latest JSON copied.');
    } catch (e) {
      alert('Clipboard access unavailable. Select and copy the JSON shown on screen.');
    }
  });

  $('nodeSelect').addEventListener('change', (e) => {
    S.node = e.target.value;
    $('nodeLabel').textContent = S.node;
    loadHistory().catch(() => {});
  });

  setInterval(() => { if (S.mode === 'live') updateStatus(); }, 10000);

  // ---------- start ----------
  (async function init() {
    try {
      const h = await api('/api/health', {}, 5000);
      S.mode = 'live';
      S.intervalMin = h.report_interval_min || 15;
      S.simEnabled = h.simulation_enabled !== false;
      $('generate').hidden = !S.simEnabled;
      S.node = null;
      await loadStats();
      if (S.nodes.length) {
        const newest = [...S.nodes].sort((a, b) => Date.parse(b.last_seen) - Date.parse(a.last_seen))[0];
        S.node = newest.node_id;
        fillNodeSelect();
        await loadHistory();
      }
      connectStream();
    } catch (e) {
      S.mode = 'demo';
      S.node = 'FIELD-01';
      S.history = [];
    }
    render();
  })();
})();
